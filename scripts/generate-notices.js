#!/usr/bin/env node
'use strict';

// Regenerates THIRD_PARTY_NOTICES.md from package-lock.json and the installed packages' own license
// files. It reads only local files. Run it after any dependency change, from a checkout that has run
// `npm ci`, and review the diff.

const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const lock = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'), 'utf8'));
const direct = new Set(Object.keys(JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).dependencies));

const entries = Object.entries(lock.packages)
  .filter(([key]) => key.startsWith('node_modules/'))
  .map(([key, value]) => ({ name: key.slice('node_modules/'.length), version: value.version, license: value.license }))
  .sort((a, b) => a.name.localeCompare(b.name));

const out = [
  '# Third-party notices',
  '',
  'This module bundles no third-party code in its own files. At install time Forge installs the packages',
  'below from `package-lock.json`, which pins each one by version and integrity hash. Their licenses are',
  'reproduced as shipped in the installed packages. This file is generated by',
  '`scripts/generate-notices.js`; do not edit it by hand.',
  '',
  '| Package | Version | License | Use |',
  '| --- | --- | --- | --- |',
  ...entries.map((entry) => `| \`${entry.name}\` | ${entry.version} | ${entry.license} | ${direct.has(entry.name) ? 'direct dependency' : 'dependency of a direct dependency'} |`),
  '',
];

for (const entry of entries) {
  const dir = path.join(root, 'node_modules', entry.name);
  const file = fs.readdirSync(dir).find((name) => /^licen[cs]e(\.md|\.txt)?$/i.test(name));
  if (!file) throw new Error(`${entry.name} ships no license file`);
  out.push(`## ${entry.name} ${entry.version}`, '', `License: ${entry.license}`, '', '```text', fs.readFileSync(path.join(dir, file), 'utf8').trim(), '```', '');
}

fs.writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), out.join('\n'));
process.stdout.write(`wrote THIRD_PARTY_NOTICES.md for ${entries.length} packages\n`);
